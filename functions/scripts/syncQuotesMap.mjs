#!/usr/bin/env node
/**
 * Generates a self-contained TypeScript quote lookup module (`src/quotesMapData.ts`)
 * inside `functions/` from `../src/data/quotes.json` so `tsc` compiles it directly
 * into `lib/quotesMapData.js` for Cloud Run / Cloud Build deployments.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const FUNCTIONS_ROOT = path.resolve(SCRIPT_DIR, '..');
const SOURCE_QUOTES_PATH = path.resolve(
  FUNCTIONS_ROOT,
  '..',
  'src',
  'data',
  'quotes.json'
);
const TARGET_TS_PATH = path.resolve(FUNCTIONS_ROOT, 'src', 'quotesMapData.ts');

if (!fs.existsSync(SOURCE_QUOTES_PATH)) {
  if (fs.existsSync(TARGET_TS_PATH)) {
    process.exit(0);
  }
  throw new Error(`Missing source quotes database at ${SOURCE_QUOTES_PATH}`);
}

const rawQuotes = JSON.parse(fs.readFileSync(SOURCE_QUOTES_PATH, 'utf8'));
const compactMap = {};
for (const entry of rawQuotes) {
  if (
    entry &&
    typeof entry.id === 'number' &&
    typeof entry.quote === 'string'
  ) {
    compactMap[entry.id] = {
      q: entry.quote,
      ...(typeof entry.tier === 'string' ? { t: entry.tier } : {}),
    };
  }
}

const tsSource = `// AUTO-GENERATED by scripts/syncQuotesMap.mjs — DO NOT EDIT\nexport const QUOTES_MAP: Readonly<Record<number, { q: string; t?: string }>> = ${JSON.stringify(compactMap)};\n`;

fs.mkdirSync(path.dirname(TARGET_TS_PATH), { recursive: true });
fs.writeFileSync(TARGET_TS_PATH, tsSource, 'utf8');
